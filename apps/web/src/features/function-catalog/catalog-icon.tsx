export function CatalogFunctionIcon({
  iconKey,
  size = CATALOG_ICON_SIZE_PX,
}: {
  iconKey: string;
  size?: number;
}) {
  const Icon = isCatalogIconKey(iconKey) ? CATALOG_ICONS[iconKey] : Layers;
  return <Icon size={size} aria-hidden className="text-foreground" />;
}

function isCatalogIconKey(iconKey: string): iconKey is DeliveryFunctionIconKey {
  return Object.prototype.hasOwnProperty.call(CATALOG_ICONS, iconKey);
}
